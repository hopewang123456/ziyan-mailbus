"""Composition root package (R2, 2026-10-26) — wire ports to adapters.

Split of the former 1835-line `lib/composition.py` into domain modules:

- `context.py`          AppContext / bundles / process context management
- `factories.py`        true build_*/get_* wiring factories
- `facade_config.py`    lazy forwarders → adapters.config / adapters.integrations
- `facade_frameworks.py`→ adapters.frameworks
- `facade_ops.py`       → adapters.ops / plane / runtime / locale
- `facade_orchestration.py` → adapters.orchestration + application orchestration bridges
- `facade_transport.py` → adapters.results / adapters.transport + delivery bridges
- `facade_llm.py`       → adapters.internal_llm + application llm bridges

This `__init__` re-exports the full historical surface (`from lib.composition
import X` keeps working unchanged); `__all__` mirrors the pre-split module.
"""
