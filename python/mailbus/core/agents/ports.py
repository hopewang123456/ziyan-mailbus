"""Agent 台账对外的仓储与目录端口（由 adapters 实现）。"""

from __future__ import annotations

from typing import Protocol, Self

from mailbus.core.agents.models import Agent, AgentInvite, AgentSummary
from mailbus.core.identity.ports import EmployeeRepository
from mailbus.core.shared.ports import OutboxPort


class TokenCipherPort(Protocol):
    """token 加解密与反查摘要端口；实现位于 adapters，application 只依赖此协议。"""

    @property
    def available(self) -> bool: ...

    def require(self) -> None: ...

    def encrypt(self, plaintext: str) -> str: ...

    def decrypt(self, ciphertext: str | None) -> str | None: ...

    def lookup_digest(self, plaintext: str) -> str: ...

    def fingerprint(self, plaintext: str) -> str: ...


class AgentRepository(Protocol):
    def get(self, agent_id: str) -> Agent | None: ...

    def save(self, agent: Agent) -> None: ...

    def list_all(self) -> list[Agent]: ...

    def list_page(self, limit: int, offset: int) -> tuple[list[Agent], int]: ...

    def find_by_token_lookup(self, lookup_hash: str) -> Agent | None: ...

    def delete(self, agent_id: str) -> None: ...

    def soft_delete(self, agent_id: str, actor_id: str, now) -> None: ...

    def add_invite(self, invite: AgentInvite) -> None: ...

    def get_invite(self, invite_id: str) -> AgentInvite | None: ...

    def get_invite_by_hash(self, code_hash: str) -> AgentInvite | None: ...

    def list_invites(self, limit: int, offset: int) -> tuple[list[AgentInvite], int]: ...

    def save_invite(self, invite: AgentInvite) -> None: ...


class AgentDirectoryPort(Protocol):
    """只读摘要查询：员工视图与布局投影使用。"""

    def summaries(self, agent_ids: tuple[str, ...]) -> dict[str, AgentSummary]: ...


class AgentsUnitOfWork(Protocol):
    """Agent 用例的事务边界；员工仓储用于绑定与解绑。"""

    outbox: OutboxPort
    agents: AgentRepository
    employees: EmployeeRepository

    def __enter__(self) -> Self: ...

    def __exit__(self, exc_type, exc, tb) -> bool | None: ...

    def commit(self) -> None: ...
